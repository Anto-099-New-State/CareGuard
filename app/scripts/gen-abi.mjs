// Copies the compiled contract ABI into lib/abi.ts as a const, so viem infers every type.
// Run after `forge build` in ../contracts:  npm run abi
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(readFileSync(new URL("../../contracts/out/CareGuardEpisode.sol/CareGuardEpisode.json", import.meta.url), "utf8"));
const out = `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.\nexport const careGuardAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync(new URL("../lib/abi.ts", import.meta.url), out);
console.log(`Wrote lib/abi.ts (${artifact.abi.length} entries)`);
